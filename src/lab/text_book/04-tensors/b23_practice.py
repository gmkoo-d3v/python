# [2권 Chapter 4. 텐서: 숫자를 담는 그릇 · 4.11 실습: 도시별 기후 패턴 비교하기 · manuscript-vol2/chapters/04-tensors.md:1334]
import torch

도시 = ["가람시", "나래시", "다솜시", "라온시", "마루시"]
# 도시 5곳 × 12개월 월평균 기온(°C). 실제 관측값이 아닌 예제용 숫자입니다.
기온 = torch.tensor([
    [-2.0,  0.5,  6.0, 12.5, 18.0, 22.5, 25.5, 26.0, 21.5, 14.5,  7.0,  0.5],
    [ 3.5,  5.0,  9.0, 14.0, 18.5, 21.5, 25.0, 26.5, 23.0, 18.0, 12.0,  6.0],
    [-4.0, -1.5,  4.5, 11.5, 17.5, 22.0, 24.5, 25.0, 19.5, 12.5,  5.0, -1.5],
    [ 6.0,  7.0, 10.0, 14.5, 18.5, 21.5, 26.0, 27.0, 23.5, 19.0, 13.5,  8.5],
    [-1.0,  1.0,  6.5, 13.0, 18.5, 23.0, 25.5, 26.5, 21.0, 14.0,  7.5,  1.0],
])
print("모양:", 기온.shape)

# 1) 도시별 연평균과 연교차(가장 더운 달 - 가장 추운 달)
연평균 = 기온.mean(dim=1)
연교차 = 기온.max(dim=1).values - 기온.min(dim=1).values
for 이름, 평균, 교차 in zip(도시, 연평균, 연교차):
    print(f"{이름}: 연평균 {평균:5.2f}°C, 연교차 {교차:4.1f}°C")




# 2) 도시마다 가장 추운 달과 그 기온 (min은 (값, 인덱스)를 함께 반환)
최저기온, 추운달 = 기온.min(dim=1)
for 이름, 달, 기온값 in zip(도시, 추운달.tolist(), 최저기온.tolist()):
    print(f"{이름}: {달+1}월 {기온값}°C")

# 3) 도시마다 가장 더운 달 (argmax는 0부터 세므로 +1)
for 이름, 달 in zip(도시, (기온.argmax(dim=1) + 1).tolist()):
    print(f"{이름}: {달}월")

# 4) 도시마다 표준화: (기온 - 그 도시 평균) / 그 도시 표준편차
평균 = 기온.mean(dim=1, keepdim=True)        # (5, 1)
표준편차 = 기온.std(dim=1, keepdim=True)     # (5, 1)
표준화 = (기온 - 평균) / 표준편차            # (5, 12) - (5, 1) → 브로드캐스팅
print("표준화 후 도시별 평균:", 표준화.mean(dim=1).abs().max() < 1e-6)

# 5) 기후 패턴이 가장 닮은 도시 찾기: 코사인 유사도 = 단위 벡터끼리의 행렬곱
단위 = 표준화 / 표준화.norm(dim=1, keepdim=True)
유사도 = 단위 @ 단위.T                       # (5, 12) @ (12, 5) → (5, 5)
유사도.fill_diagonal_(-1.0)                  # 자기 자신은 빼기
짝 = 유사도.argmax(dim=1)
for i, j in enumerate(짝.tolist()):
    print(f"{도시[i]}와 가장 닮은 도시: {도시[j]} (유사도 {유사도[i, j]:.4f})")

# 6) 도시마다 가장 더운 석 달 (topk는 큰 순서로 주므로 달 순서로 다시 정렬)
더운_석달 = 기온.topk(3, dim=1).indices.sort(dim=1).values + 1
for 이름, 달 in zip(도시, 더운_석달.tolist()):
    print(f"{이름}의 가장 더운 석 달: {달}월")

# 7) 난방 지수: 10도보다 추운 만큼을 달마다 더한 값 (예제용 지표)
난방 = torch.where(기온 < 10, 10 - 기온, 0.0)
print("난방이 필요한 달 수:", (기온 < 10).sum(dim=1).tolist())
print("난방 지수:", 난방.sum(dim=1).tolist())
print("clamp로 계산해도 같은가:", torch.equal(난방, (10 - 기온).clamp(min=0)))

# 8) 월별 다섯 도시의 평균 기온 (dim=0: 도시 방향으로 평균)
월평균 = 기온.mean(dim=0)
print("월별 평균 기온:", [f"{t:.1f}" for t in 월평균.tolist()])
print("모양:", 월평균.shape)



# 9) 영하인 달이 도시마다 몇 개 있는지
영하_개수 = (기온 < 0).sum(dim=1)
for 이름, 개수 in zip(도시, 영하_개수.tolist()):
    print(f"{이름}: 영하 {개수}개월")

# 10) 연교차가 가장 큰 도시
연교차_최대_도시 = 연교차.argmax()
print(f"연교차가 가장 큰 도시: {도시[연교차_최대_도시.item()]} ({연교차[연교차_최대_도시]:.1f}°C)")

# 11) 난방 기준을 15도로 올리면 난방 지수와 달 수
난방15 = torch.where(기온 < 15, 15 - 기온, 0.0)
난방15_달수 = (기온 < 15).sum(dim=1)
for 이름, 지수, 달수 in zip(도시, 난방15.sum(dim=1).tolist(), 난방15_달수.tolist()):
    print(f"{이름}: 난방지수 {지수:.1f}, {달수}개월")

# 12) 유사도 행렬에서 fill_diagonal_(-1.0)을 지우면?
# 대각선이 1.0(자기 자신)으로 가장 크므로, argmax로 찾으면 자기 자신이 됨
유사도_원본 = 단위 @ 단위.T
짝_원본 = 유사도_원본.argmax(dim=1)
print("fill_diagonal_ 없이 짝 찾기:")
for i, j in enumerate(짝_원본.tolist()):
    print(f"  {도시[i]}와 가장 닮은 도시: {도시[j]} (자기 자신)")

# 13) 계절별 묶기: 겨울(12~2월) 봄(3~5월) 여름(6~8월) 가을(9~11월) → 모양 (5, 4)
계절_인덱스 = [
    [11, 0, 1],      # 겨울: 12월, 1월, 2월
    [2, 3, 4],        # 봄: 3월, 4월, 5월
    [5, 6, 7],        # 여름: 6월, 7월, 8월
    [8, 9, 10],       # 가을: 9월, 10월, 11월
]
계절기온 = torch.stack([기온[:, idx].mean(dim=1) for idx in 계절_인덱스], dim=1)  # (4, 5) → (5, 4)
print("계절기온 모양:", 계절기온.shape)
계절이름 = ["겨울", "봄", "여름", "가을"]
for 이름, 기온들 in zip(도시, 계절기온.tolist()):
    print(f"{이름}: {', '.join(f'{s}={t:.1f}°C' for s, t in zip(계절이름, 기온들))}")

# 14) 전달(이전 달)보다 가장 많이 오른 달과 내린 달
# 각 달과 이전 달의 차이: 1월은 이전 달이 없으므로 2월~12월만 계산 (인덱스 1~11)
변화 = 기온[:, 1:] - 기온[:, :-1]           # (5, 11): 2월 대비 1월, 3월 대비 2월, ..., 12월 대비 11월
# 변화 > 0이면 상승, < 0이면 하강
가장_오른_폭 = 변화.max(dim=1)              # (values, indices) → indices는 0=2월, 1=3월, ...
가장_내린_폭 = 변화.min(dim=1)              # min은 가장 큰 하강(음수 중 가장 작은 값)

for 이름 in 도시:
    idx = 도시.index(이름)
    오른_달 = 가장_오른_폭.indices[idx].item() + 2   # +2: 인덱스 0→2월, 1→3월, ...
    오른_폭 = 가장_오른_폭.values[idx].item()
    내린_달 = 가장_내린_폭.indices[idx].item() + 2
    내린_폭 = 가장_내린_폭.values[idx].item()
    print(f"{이름}: 가장 많이 오른 달 {오른_달}월 (+{오른_폭:.1f}°C), 가장 많이 내린 달 {내린_달}월 ({내린_폭:.1f}°C)")

