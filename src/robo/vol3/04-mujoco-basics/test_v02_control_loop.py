"""v02_control_loop.py 테스트 시나리오 (pytest).

시나리오 (교안 33번 슬라이드 "제어 루프 설계"의 숫자와 같아야 한다)
1. 장면: 관절 1개, motor 액추에이터 1개, 처음 각도 0도(수평).
2. 처음 몇 걸음은 오차가 커서 토크가 크다(약 42N·m = 40 × 60°).
3. 2초 뒤 각도는 56.1도 근처: 목표 60도보다 3.9도 처진다.
4. 2초 뒤 토크는 약 2.74N·m = 추의 무게가 만드는 토크(1 × 9.81 × 0.5 × cos56.1°).
5. kp를 키우면 처짐이 줄어든다(같은 장면, kp 400).
"""
import numpy as np

from v02_control_loop import 장면_만들기, 제어_루프


def test_장면_구성():
    모델, 데이터 = 장면_만들기()
    assert 모델.njnt == 1 and 모델.nu == 1
    assert 데이터.qpos[0] == 0.0


def test_처음_토크는_크다():
    기록 = 제어_루프(초=0.01)
    assert abs(기록["토크"][0] - 40 * np.deg2rad(60)) < 0.1      # 41.9N·m


def test_2초뒤_각도_처짐():
    기록 = 제어_루프(초=2.0)
    assert abs(기록["각도_도"][-1] - 56.1) < 0.15


def test_2초뒤_토크는_무게_토크():
    기록 = 제어_루프(초=2.0)
    무게_토크 = 1.0 * 9.81 * 0.5 * np.cos(np.deg2rad(기록["각도_도"][-1]))
    assert abs(기록["토크"][-1] - 무게_토크) < 0.05
    assert abs(기록["토크"][-1] - 2.74) < 0.03


def test_kp_키우면_덜_처진다():
    약함 = 제어_루프(초=2.0, kp=40)
    셈 = 제어_루프(초=2.0, kp=400, kd=12)
    assert (60 - 셈["각도_도"][-1]) < (60 - 약함["각도_도"][-1]) / 5
